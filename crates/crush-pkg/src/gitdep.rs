//! Git dependencies (CRUSH-351).
//!
//! ```toml
//! [[dependencies]]
//! name = "facet"
//! git  = "https://github.com/nixpt/facet"
//! tag  = "v0.1.1"          # or rev = "<sha>" / branch = "<name>"
//! ```
//!
//! A git dependency is fetched into a cache, checked out at one exact
//! commit, and from there treated exactly like a path dependency (its
//! `capsule.toml` entry is concatenated into the program). The commit a
//! `tag`/`branch` resolved to is recorded in `capsule.lock`, so later builds
//! are reproducible even if the tag moves or the branch advances.
//!
//! Everything goes through the `git` CLI (no libgit2).
//!
//! ## Cache layout
//!
//! ```text
//! $CRUSH_PKG_CACHE            (else $XDG_CACHE_HOME/crush-pkg, else ~/.cache/crush-pkg)
//! └── git/<host>/<repo>-<urlhash8>/<full-commit-sha>/    checked-out tree, no .git
//!                                  └── .crush-pkg-rev     marker: complete checkout
//! ```
//!
//! ## Lockfile (`capsule.lock`, next to `capsule.toml`; commit it)
//!
//! ```toml
//! version = 1
//!
//! [[git]]
//! name = "facet"
//! url = "https://github.com/nixpt/facet"
//! ref = "tag:v0.1.1"
//! rev = "4b9046a…(40 hex)"
//! ```

use std::path::{Path, PathBuf};
use std::process::Command;

use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};

use crate::manifest::Dependency;

pub const LOCK_FILE: &str = "capsule.lock";
const MARKER: &str = ".crush-pkg-rev";

/// One pinned git dependency in `capsule.lock`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct LockEntry {
    pub name: String,
    pub url: String,
    /// `tag:<t>`, `branch:<b>` or `rev:<r>` — what the manifest asked for.
    #[serde(rename = "ref")]
    pub reference: String,
    /// The full commit the reference resolved to.
    pub rev: String,
}

#[derive(Debug, Default, Serialize, Deserialize)]
struct LockFile {
    #[serde(default)]
    version: u32,
    #[serde(default, rename = "git")]
    git: Vec<LockEntry>,
}

/// `capsule.lock` entries for `root`; empty when the file is absent.
pub fn read_lock(root: &Path) -> anyhow::Result<Vec<LockEntry>> {
    let path = root.join(LOCK_FILE);
    if !path.exists() {
        return Ok(Vec::new());
    }
    let text = std::fs::read_to_string(&path)?;
    let lock: LockFile = toml::from_str(&text)
        .map_err(|e| anyhow::anyhow!("{} is not a valid lockfile: {e}", path.display()))?;
    Ok(lock.git)
}

/// Write `capsule.lock` (or remove it when no git dependency is left).
/// Leaves the file untouched when the content would not change.
pub fn write_lock(root: &Path, entries: &[LockEntry]) -> anyhow::Result<()> {
    let path = root.join(LOCK_FILE);
    if entries.is_empty() {
        if path.exists() {
            std::fs::remove_file(&path)?;
        }
        return Ok(());
    }
    let lock = LockFile { version: 1, git: entries.to_vec() };
    let body = toml::to_string(&lock)?;
    let text = format!("# Generated by crush-pkg. Pins git dependencies; commit this file.\n{body}");
    if std::fs::read_to_string(&path).ok().as_deref() != Some(text.as_str()) {
        std::fs::write(&path, text)?;
    }
    Ok(())
}

/// What a git dependency asks for: `("tag"|"branch"|"rev", value)`.
fn reference(dep: &Dependency) -> anyhow::Result<(&'static str, &str)> {
    match (&dep.tag, &dep.branch, &dep.rev) {
        (Some(t), None, None) => Ok(("tag", t)),
        (None, Some(b), None) => Ok(("branch", b)),
        (None, None, Some(r)) => Ok(("rev", r)),
        _ => anyhow::bail!(
            "dependency '{}': a git dependency needs exactly one of `tag`, `rev` or `branch`",
            dep.name
        ),
    }
}

/// The `ref` string stored in the lockfile for `dep`.
pub fn ref_string(dep: &Dependency) -> anyhow::Result<String> {
    let (kind, value) = reference(dep)?;
    Ok(format!("{kind}:{value}"))
}

/// The cache root (see the module docs).
pub fn cache_root() -> PathBuf {
    if let Some(dir) = std::env::var_os("CRUSH_PKG_CACHE").filter(|v| !v.is_empty()) {
        return PathBuf::from(dir);
    }
    if let Some(dir) = std::env::var_os("XDG_CACHE_HOME").filter(|v| !v.is_empty()) {
        return PathBuf::from(dir).join("crush-pkg");
    }
    let home = std::env::var_os("HOME").map(PathBuf::from).unwrap_or_else(std::env::temp_dir);
    home.join(".cache").join("crush-pkg")
}

fn sanitize(s: &str) -> String {
    let cleaned: String = s
        .chars()
        .map(|c| if c.is_ascii_alphanumeric() || matches!(c, '.' | '_' | '-') { c } else { '_' })
        .collect();
    let cleaned = cleaned.trim_matches('.').to_string();
    if cleaned.is_empty() { "_".to_string() } else { cleaned }
}

/// `git/<host>/<repo>-<urlhash8>` under the cache root.
fn repo_cache_dir(url: &str) -> PathBuf {
    let rest = url.split_once("://").map(|(_, r)| r).unwrap_or(url);
    // scp-like `git@host:owner/repo.git` -> `host/owner/repo.git`
    let rest = rest.rsplit_once('@').map(|(_, r)| r).unwrap_or(rest).replace(':', "/");
    let mut parts = rest.trim_matches('/').split('/').filter(|p| !p.is_empty());
    let host = if url.starts_with("file://") || !url.contains("://") && !url.contains('@') {
        "local".to_string()
    } else {
        sanitize(parts.next().unwrap_or("unknown"))
    };
    let repo = parts.next_back().unwrap_or("repo").trim_end_matches(".git");
    let hash = hex::encode(Sha256::digest(url.as_bytes()));
    cache_root().join("git").join(host).join(format!("{}-{}", sanitize(repo), &hash[..8]))
}

fn is_full_sha(s: &str) -> bool {
    s.len() == 40 && s.bytes().all(|b| b.is_ascii_hexdigit())
}

/// Run `git`, returning stdout on success or a short stderr on failure.
fn git(dir: Option<&Path>, args: &[&str]) -> Result<String, String> {
    let mut cmd = Command::new("git");
    cmd.args(args)
        .env("GIT_TERMINAL_PROMPT", "0")
        .stdin(std::process::Stdio::null());
    if let Some(d) = dir {
        cmd.current_dir(d);
    }
    let out = cmd.output().map_err(|e| {
        if e.kind() == std::io::ErrorKind::NotFound {
            "the `git` command was not found on PATH (git dependencies need git installed)".to_string()
        } else {
            format!("could not run git: {e}")
        }
    })?;
    if out.status.success() {
        Ok(String::from_utf8_lossy(&out.stdout).into_owned())
    } else {
        let err = String::from_utf8_lossy(&out.stderr);
        let line = err.lines().rev().find(|l| !l.trim().is_empty()).unwrap_or("git failed");
        Err(line.trim().to_string())
    }
}

fn network_error(dep: &Dependency, url: &str, why: &str) -> anyhow::Error {
    anyhow::anyhow!(
        "dependency '{}': could not reach {url}: {why}\n  \
         check the network, or pass --offline to build from the local cache only",
        dep.name
    )
}

/// Resolve a `tag`/`branch` to a commit via `git ls-remote` (no clone).
fn ls_remote(dep: &Dependency, url: &str, kind: &str, value: &str) -> anyhow::Result<String> {
    let (ref_name, peeled) = match kind {
        "tag" => (format!("refs/tags/{value}"), Some(format!("refs/tags/{value}^{{}}"))),
        _ => (format!("refs/heads/{value}"), None),
    };
    let mut args = vec!["ls-remote", url, ref_name.as_str()];
    if let Some(p) = &peeled {
        args.push(p.as_str());
    }
    let out = git(None, &args).map_err(|e| network_error(dep, url, &e))?;
    let mut plain = None;
    let mut peeled_sha = None;
    for line in out.lines() {
        let Some((sha, name)) = line.split_once('\t') else { continue };
        if peeled.as_deref() == Some(name) {
            peeled_sha = Some(sha.to_string());
        } else if name == ref_name {
            plain = Some(sha.to_string());
        }
    }
    peeled_sha.or(plain).ok_or_else(|| {
        anyhow::anyhow!("dependency '{}': {kind} `{value}` not found in {url}", dep.name)
    })
}

/// Fetch `want` (a full sha, or any rev for `full`) into a scratch checkout
/// and move the tree into the cache. Returns the resolved full sha.
fn fetch_checkout(dep: &Dependency, url: &str, repo_dir: &Path, want: &str) -> anyhow::Result<String> {
    std::fs::create_dir_all(repo_dir)?;
    let tmp = repo_dir.join(format!(".tmp-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&tmp);
    std::fs::create_dir_all(&tmp)?;
    let result = (|| -> anyhow::Result<String> {
        let ctx = |e: String| network_error(dep, url, &e);
        git(Some(&tmp), &["init", "-q"]).map_err(|e| anyhow::anyhow!("dependency '{}': {e}", dep.name))?;
        git(Some(&tmp), &["remote", "add", "origin", url]).map_err(|e| anyhow::anyhow!("{e}"))?;
        // Shallow when the commit is known exactly; otherwise (or when the
        // server refuses to serve a bare sha) fetch the lot.
        let shallow = is_full_sha(want)
            && git(Some(&tmp), &["fetch", "-q", "--depth", "1", "origin", want]).is_ok();
        if !shallow {
            git(
                Some(&tmp),
                &["fetch", "-q", "origin", "+refs/heads/*:refs/remotes/origin/*", "+refs/tags/*:refs/tags/*"],
            )
            .map_err(ctx)?;
        }
        let rev = git(Some(&tmp), &["rev-parse", "--verify", &format!("{want}^{{commit}}")])
            .map_err(|_| anyhow::anyhow!("dependency '{}': revision `{want}` not found in {url}", dep.name))?
            .trim()
            .to_string();
        git(Some(&tmp), &["-c", "advice.detachedHead=false", "checkout", "-q", "--detach", &rev])
            .map_err(|e| anyhow::anyhow!("dependency '{}': checkout of {rev} failed: {e}", dep.name))?;
        let _ = std::fs::remove_dir_all(tmp.join(".git"));
        std::fs::write(tmp.join(MARKER), &rev)?;
        let dest = repo_dir.join(&rev);
        if dest.join(MARKER).exists() {
            let _ = std::fs::remove_dir_all(&tmp); // lost a race: same content
        } else {
            let _ = std::fs::remove_dir_all(&dest);
            std::fs::rename(&tmp, &dest)?;
        }
        Ok(rev)
    })();
    if result.is_err() {
        let _ = std::fs::remove_dir_all(&tmp);
    }
    result
}

/// Where `dep` is (or would be) checked out for `rev`, if that is complete.
fn cached(url: &str, rev: &str) -> Option<PathBuf> {
    let dir = repo_cache_dir(url).join(rev);
    dir.join(MARKER).is_file().then_some(dir)
}

/// The already-fetched checkout for `dep` according to the lockfile — no
/// network, no writes. Used by the unused-dependency lint.
pub fn locked_checkout(root: &Path, dep: &Dependency) -> Option<PathBuf> {
    let url = dep.git.as_deref()?;
    let want = ref_string(dep).ok()?;
    let lock = read_lock(root).ok()?;
    let entry = lock.iter().find(|e| e.name == dep.name && e.url == url && e.reference == want)?;
    cached(url, &entry.rev)
}

/// Resolve a git dependency to a checked-out directory and the commit it
/// is pinned to. A matching `capsule.lock` entry wins over the network;
/// `offline` forbids touching the network at all.
pub fn resolve(
    dep: &Dependency,
    locked: Option<&LockEntry>,
    offline: bool,
) -> anyhow::Result<(PathBuf, LockEntry)> {
    let url = dep.git.as_deref().ok_or_else(|| anyhow::anyhow!("dependency '{}' has no `git` url", dep.name))?;
    let (kind, value) = reference(dep)?;
    let want_ref = format!("{kind}:{value}");
    let pinned = locked
        .filter(|l| l.name == dep.name && l.url == url && l.reference == want_ref && is_full_sha(&l.rev))
        .map(|l| l.rev.clone())
        .or_else(|| (kind == "rev" && is_full_sha(value)).then(|| value.to_ascii_lowercase()));

    let mk = |rev: String| LockEntry { name: dep.name.clone(), url: url.to_string(), reference: want_ref.clone(), rev };

    if let Some(rev) = pinned {
        if let Some(dir) = cached(url, &rev) {
            return Ok((dir, mk(rev)));
        }
        if offline {
            anyhow::bail!(
                "dependency '{}': {rev} of {url} is not in the cache ({}) and --offline forbids fetching it; \
                 run once without --offline",
                dep.name,
                repo_cache_dir(url).display()
            );
        }
        let got = fetch_checkout(dep, url, &repo_cache_dir(url), &rev)?;
        return Ok((repo_cache_dir(url).join(&got), mk(got)));
    }

    if offline {
        anyhow::bail!(
            "dependency '{}': {kind} `{value}` of {url} is not pinned in {LOCK_FILE} and --offline forbids \
             contacting the remote; run once without --offline",
            dep.name
        );
    }
    let want = if kind == "rev" { value.to_string() } else { ls_remote(dep, url, kind, value)? };
    if let Some(dir) = cached(url, &want) {
        return Ok((dir, mk(want)));
    }
    let got = fetch_checkout(dep, url, &repo_cache_dir(url), &want)?;
    Ok((repo_cache_dir(url).join(&got), mk(got)))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn cache_dir_is_host_repo_hash() {
        let a = repo_cache_dir("https://github.com/nixpt/facet");
        let s = a.to_string_lossy();
        assert!(s.contains("/git/github.com/facet-"), "{s}");
        assert_ne!(a, repo_cache_dir("https://github.com/other/facet"));
        let f = repo_cache_dir("file:///tmp/x/facet");
        assert!(f.to_string_lossy().contains("/git/local/facet-"), "{f:?}");
    }

    #[test]
    fn full_sha_detection() {
        assert!(is_full_sha("4b9046a0000000000000000000000000000000ff"));
        assert!(!is_full_sha("4b9046a"));
    }
}
